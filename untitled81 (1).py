import numpy as np  # NumPy Documentation: https://numpy.org/doc/stable/
import matplotlib.pyplot as plt  # Matplotlib Documentation: https://matplotlib.org/stable/users/index.html
from numba import jit, prange  # Numba Documentation: https://numba.readthedocs.io/
import time  # Python Time Module: https://docs.python.org/3/library/time.html

# Configuration
num_dumbbells = 50  # Number of dumbbells (each dumbbell = 2 spheres): https://doi.org/10.1103/PhysRevE.74.061308
radius = 1.0  # Sphere radius
L_ratios = [1.0, 1.5, 2.0, 2.5]  # Separation to radius ratios: https://journals.aps.org/pre/abstract/10.1103/PhysRevE.68.011306
densities = [0.30, 0.38, 0.45, 0.52, 0.59, 0.63, 0.64, 0.69, 0.72]  # Range of densities
num_configurations = 5  # Number of configurations per density
density_threshold = 0.65  # Jamming density threshold: https://journals.aps.org/prl/abstract/10.1103/PhysRevLett.88.075507

@jit(nopython=True, fastmath=True, parallel=True)
def compute_energy_and_gradient(dumbbells, box_size, density, L):
    """
    Compute energy and gradient with periodic boundary conditions for dumbbell particles.
    Reference: https://doi.org/10.1063/1.445869
    """
    n = len(dumbbells) // 6  # Each dumbbell has 2 spheres (6 coordinates)
    dumbbells = dumbbells.reshape(n, 2, 3)  # Reshape to (n, 2, 3) for dumbbells

    gradient = np.zeros((2 * n, 3))  # Gradient for 2 spheres per dumbbell
    energy = 0.0

    for i in prange(n):
        for j in range(i + 1, n):
            for k1 in range(2):  # Sphere 1 of dumbbell i
                for k2 in range(2):  # Sphere 2 of dumbbell j
                    rij = dumbbells[i, k1] - dumbbells[j, k2]
                    rij = rij - box_size * np.round(rij / box_size)  # Apply periodic boundaries
                    dist2 = np.sum(rij * rij)

                    if dist2 < (2 * radius) ** 2:  # Interaction range (soft spheres)
                        dist = np.sqrt(dist2)
                        overlap = 2 * radius - dist
                        if overlap > 0:  # Only consider overlaps
                            if density < density_threshold:
                                energy += 0  # No energy penalty below threshold
                            else:
                                energy += overlap**2  # Energy penalty for overlaps

                            grad_mag = 2 * overlap / dist  # Gradient magnitude
                            gradient[i * 2 + k1] += grad_mag * rij
                            gradient[j * 2 + k2] -= grad_mag * rij

        # Enforce dumbbell constraint: fixed distance L between spheres
        r12 = dumbbells[i, 0] - dumbbells[i, 1]  # Vector between the two spheres of a dumbbell
        dist2 = np.sum(r12 * r12)
        dist = np.sqrt(dist2)
        constraint_violation = dist - L  # Violation of fixed length
        grad_mag = 2 * constraint_violation / dist
        gradient[i * 2] += grad_mag * r12
        gradient[i * 2 + 1] -= grad_mag * r12

    return energy, gradient.flatten()

@jit(nopython=True)
def line_search(dumbbells, direction, grad, box_size, density, L, alpha_init=1.0, c1=1e-6, tau=0.7):
    """
    Backtracking line search with stricter conditions.
    Reference: https://doi.org/10.1007/BF01589116
    """
    alpha = alpha_init
    f0, _ = compute_energy_and_gradient(dumbbells, box_size, density, L)
    descent = np.dot(grad, direction)

    for _ in range(10):  # Backtracking loop
        new_dumbbells = dumbbells + alpha * direction
        f_new, _ = compute_energy_and_gradient(new_dumbbells, box_size, density, L)
        if f_new <= f0 + c1 * alpha * descent:
            break
        alpha *= tau

    return alpha

@jit(nopython=True)
def nonlinear_conjugate_gradient(dumbbells, box_size, density, L, max_iter=50, tol=1e-6):
    """
    Nonlinear Conjugate Gradient with Polak-Ribiere.
    Reference: http://www.cs.cmu.edu/~quake-papers/painless-conjugate-gradient.pdf
    """
    dumbbells = dumbbells.flatten()
    _, grad = compute_energy_and_gradient(dumbbells, box_size, density, L)
    direction = -grad
    rsold = np.dot(grad, grad)

    for _ in range(max_iter):
        alpha = line_search(dumbbells, direction, grad, box_size, density, L)
        new_dumbbells = dumbbells + alpha * direction
        new_dumbbells = new_dumbbells.reshape(-1, 2, 3) % box_size  # Apply periodic boundaries
        new_dumbbells = new_dumbbells.flatten()

        _, new_grad = compute_energy_and_gradient(new_dumbbells, box_size, density, L)
        rsnew = np.dot(new_grad, new_grad)

        if rsnew < tol**2:
            break

        beta = max(0, np.dot(new_grad, new_grad - grad) / rsold)  # Polak-Ribiere beta
        direction = -new_grad + beta * direction
        grad = new_grad
        rsold = rsnew
        dumbbells = new_dumbbells

    return dumbbells.reshape(-1, 2, 3)

def initialize_dumbbells_random(box_size, num_dumbbells, L):
    """
    Initialize random positions for dumbbells.
    Reference: https://doi.org/10.1103/PhysRevE.70.043301
    """
    dumbbells = []
    for _ in range(num_dumbbells):
        center = np.random.uniform(0, box_size, 3)  # Random center
        direction = np.random.uniform(-1, 1, 3)  # Random direction
        direction /= np.linalg.norm(direction)  # Normalize
        offset = (L / 2) * direction
        dumbbells.append([center - offset, center + offset])  # Two spheres forming the dumbbell
    return np.array(dumbbells)

def optimize_dumbbells():
    """
    Optimize dumbbell configurations for various L/R ratios and densities.
    Reference: https://doi.org/10.1103/PhysRevLett.88.075507
    """
    plt.figure(figsize=(10, 6))
    for L_ratio in L_ratios:
        L = L_ratio * radius  # Compute separation L based on L/R ratio
        energy_per_density = {density: [] for density in densities}

        for density in densities:
            volume_per_dumbbell = 2 * (4 / 3) * np.pi * radius**3  # Volume of two spheres
            total_volume = num_dumbbells * volume_per_dumbbell
            box_size = (total_volume / density) ** (1 / 3)

            for config in range(num_configurations):
                dumbbells = initialize_dumbbells_random(box_size, num_dumbbells, L)
                final_dumbbells = nonlinear_conjugate_gradient(dumbbells.copy(), box_size, density, L)
                final_energy, _ = compute_energy_and_gradient(final_dumbbells.flatten(), box_size, density, L)
                energy_per_density[density].append(final_energy)

        densities_list = sorted(densities)
        avg_energies = [np.mean(energy_per_density[d]) for d in densities_list]
        std_energies = [np.std(energy_per_density[d]) for d in densities_list]

        plt.errorbar(densities_list, avg_energies, yerr=std_energies, fmt='o-', capsize=5, label=f"L/R = {L_ratio:.1f}")

    plt.xlabel('Density')  # X-axis label
    plt.ylabel('Average Energy')  # Y-axis label
    plt.title('Average Energy vs Density for Dumbbells')  # Title
    plt.grid(True)
    plt.legend()
    plt.tight_layout()
    plt.show()

if __name__ == "__main__":
    optimize_dumbbells()