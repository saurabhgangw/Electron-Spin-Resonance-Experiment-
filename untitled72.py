import numpy as np
import matplotlib.pyplot as plt
from mpl_toolkits.mplot3d import Axes3D

# Number of particles
num_particles = 100
# Radius of the spherical particles
radius = 1.0
# Desired density
desired_density = 0.64

# Calculate the volume required to achieve the desired density
volume_per_particle = (4/3) * np.pi * radius**3
total_volume_particles = num_particles * volume_per_particle
bounding_box_volume = total_volume_particles / desired_density
bounding_box_side_length = bounding_box_volume**(1/3)

# Generate initial random positions for particles within the calculated cube
initial_positions = np.random.rand(num_particles, 3) * bounding_box_side_length

# Define the objective function to minimize
def objective_function(positions):
    positions = positions.reshape((num_particles, 3))
    total_energy = 0.0

    for i in range(num_particles):
        for j in range(i + 1, num_particles):
            # Compute the distance between particles
            distance = np.linalg.norm(positions[i] - positions[j])
            # Compute the overlap (if any)
            overlap = 2 * radius - distance
            if overlap > 0:
                # Add a penalty for overlapping particles
                total_energy += overlap**2 #addding overlap (if any) to the variable 'total energy' every iteration of the for loop

    # # Add penalties for particles outside the bounding box
    # for i in range(num_particles):
    #     for d in range(3):  # Check x, y, z coordinates
    #         if positions[i, d] < 0:
    #             total_energy += (positions[i, d])**2
    #         elif positions[i, d] > bounding_box_side_length:
    #             total_energy += (positions[i, d] - bounding_box_side_length)**2

    return total_energy

# Define the gradient of the objective function
def gradient(positions):
    positions = positions.reshape((num_particles, 3))
    grad = np.zeros_like(positions)

    for i in range(num_particles):
        for j in range(num_particles):
            if i != j:
                # Compute the distance between particles
                distance = np.linalg.norm(positions[i] - positions[j])
                # Compute the overlap (if any)
                overlap = 2 * radius - distance
                if overlap > 0:
                    # Compute the gradient contribution for overlapping particles
                    grad_contribution = 2 * overlap * (positions[i] - positions[j]) / distance
                    grad[i] += grad_contribution

    # Add gradient contributions for particles outside the bounding box
    # for i in range(num_particles):
