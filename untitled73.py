import numpy as np
import matplotlib.pyplot as plt
from numba import jit
import time

num_particles = 100
radius = 1.0
densities = [0.56, 0.59, 0.62, 0.65, 0.68]  # Modified densities with 0.03 spacing

@jit(nopython=True, fastmath=True)
def compute_energy_and_gradient(positions, box_size):
    """Compute energy and gradient with periodic boundary conditions"""
    n = len(positions) // 3
    positions = positions.reshape(n, 3)
    gradient = np.zeros_like(positions)
    energy = 0.0

    for i in range(n):
        for j in range(i+1, n):
            rij = positions[i] - positions[j]
            rij = rij - box_size * np.round(rij / box_size)
            dist2 = np.sum(rij * rij)

            if dist2 < 4*radius*radius:
                dist = np.sqrt(dist2)
                overlap = 2*radius - dist
                energy += overlap * overlap
                grad_mag = 2 * overlap / dist
                gradient[i] += grad_mag * rij
                gradient[j] -= grad_mag * rij

    return energy, gradient.flatten()

@jit(nopython=True)
def line_search(positions, direction, grad, box_size, alpha_init=1.0, c1=1e-6, tau=0.7):
    """Backtracking line search with stricter conditions"""
    alpha = alpha_init
    f0, _ = compute_energy_and_gradient(positions, box_size)
    descent = np.dot(grad, direction)

    for _ in range(20):
        new_positions = positions + alpha * direction
        f_new, _ = compute_energy_and_gradient(new_positions, box_size)
        if f_new <= f0 + c1 * alpha * descent:
            break
        alpha *= tau

    return alpha

@jit(nopython=True)
def nonlinear_conjugate_gradient(positions, box_size, max_iter=100, tol=1e-7):
    """Nonlinear Conjugate Gradient with Polak-Ribiere"""
    positions = positions.flatten()
    _, grad = compute_energy_and_gradient(positions, box_size)
    direction = -grad
    rsold = np.dot(grad, grad)

    for iter_num in range(max_iter):
        alpha = line_search(positions, direction, grad, box_size)
        new_positions = positions + alpha * direction
        new_positions = new_positions.reshape(-1, 3)
        new_positions = new_positions % box_size
        new_positions = new_positions.flatten()

        _, new_grad = compute_energy_and_gradient(new_positions, box_size)
        rsnew = np.dot(new_grad, new_grad)

        if np.sqrt(rsnew) < tol:
            break

        beta = max(0, np.dot(new_grad, new_grad - grad) / rsold)
        direction = -new_grad + beta * direction

        positions = new_positions
        grad = new_grad
        rsold = rsnew

    return positions.reshape(-1, 3)

def optimize_all_densities():
    """Optimize particle positions for all densities and calculate average energies"""
    num_configurations = 10
    energy_per_density = {density: [] for density in densities}

    print("Starting optimization for all densities...")
    start_time = time.time()

    for density in densities:
        print(f"\nOptimizing for density: {density}")

        # Calculate box size
        volume_per_particle = (4/3) * np.pi * radius**3
        total_volume = num_particles * volume_per_particle
        box_size = (total_volume / density) ** (1/3)

        # Generate multiple configurations for this density
        for config in range(num_configurations):
            print(f"Configuration {config + 1}/{num_configurations}")

            # Initialize positions completely randomly
            positions = np.random.uniform(0, box_size, (num_particles, 3))

            final_positions = nonlinear_conjugate_gradient(positions.copy(), box_size)

            # Calculate final energy for this configuration
            final_energy, _ = compute_energy_and_gradient(final_positions.flatten(), box_size)
            energy_per_density[density].append(final_energy)

    end_time = time.time()
    print(f"\nTotal optimization time: {end_time - start_time:.2f} seconds")

    # Calculate and plot average energies
    densities_list = sorted(densities)
    avg_energies = [np.mean(energy_per_density[d]) for d in densities_list]
    std_energies = [np.std(energy_per_density[d]) for d in densities_list]

    # Create figure with two subplots
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(15, 6))

    # Plot average energies vs density
    ax1.errorbar(densities_list, avg_energies, yerr=std_energies, fmt='o-', capsize=5)
    ax1.set_xlabel('Density')
    ax1.set_ylabel('Average Energy')
    ax1.set_title('Average Energy vs Density\n(with standard deviation)')
    #ax1.grid(True)

    # Plot energy distribution for each density
    violin_parts = ax2.violinplot([energy_per_density[d] for d in densities_list],
                                positions=densities_list)
    ax2.set_xlabel('Density')
    ax2.set_ylabel('Energy')
    ax2.set_title('Energy Distribution per Density')
    #ax2.grid(True)

    plt.tight_layout()

    # Print numerical results
    print("\nResults for each density:")
    for density in densities_list:
        mean_energy = np.mean(energy_per_density[density])
        std_energy = np.std(energy_per_density[density])
        print(f"Density {density:.2f}:")
        print(f"  Average Energy: {mean_energy:.4f} ± {std_energy:.4f}")
        print(f"  All energies: {energy_per_density[density]}")

    plt.show()

if __name__ == "__main__":
    optimize_all_densities()