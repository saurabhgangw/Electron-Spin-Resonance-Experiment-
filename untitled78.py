import numpy as np
import matplotlib.pyplot as plt
from numba import jit, prange
import scipy.stats
import time
from datetime import datetime

# Configuration
num_dumbbells = 50  # Number of dumbbells
radius = 1.0
densities = [0.30, 0.38, 0.45, 0.52, 0.59, 0.63, 0.64, 0.69, 0.72]
num_configurations = 5
L = 1.5  # Distance between dumbbell spheres
density_threshold = 0.65

@jit(nopython=True, fastmath=True, parallel=True)
def compute_energy_and_gradient(dumbbells, box_size, density, L):
    """Compute energy and gradient for dumbbells with periodic boundary conditions."""
    n = len(dumbbells) // (2 * 3)
    dumbbells = dumbbells.reshape(n, 2, 3)
    gradient = np.zeros_like(dumbbells)
    energy = 0.0

    for i in prange(n):
        for j in range(i + 1, n):
            for k1 in range(2):
                for k2 in range(2):
                    rij = dumbbells[i, k1] - dumbbells[j, k2]
                    rij = rij - box_size * np.round(rij / box_size)
                    dist2 = np.sum(rij * rij)

                    if dist2 < 4 * radius * radius:
                        dist = np.sqrt(dist2)
                        overlap = 2 * radius - dist
                        if overlap > 0:
                            if density < density_threshold:
                                energy += 0
                            else:
                                energy += overlap ** 2

                            grad_mag = 2 * overlap / dist
                            gradient[i, k1] += grad_mag * rij
                            gradient[j, k2] -= grad_mag * rij

    return energy, gradient.flatten()

@jit(nopython=True)
def line_search(dumbbells, direction, grad, box_size, density, L, alpha_init=1.0, c1=1e-6, tau=0.7):
    """Backtracking line search for dumbbells."""
    alpha = alpha_init
    f0, _ = compute_energy_and_gradient(dumbbells, box_size, density, L)
    descent = np.dot(grad, direction)

    for _ in range(10):
        new_dumbbells = dumbbells + alpha * direction
        f_new, _ = compute_energy_and_gradient(new_dumbbells, box_size, density, L)
        if f_new <= f0 + c1 * alpha * descent:
            break
        alpha *= tau

    return alpha

@jit(nopython=True)
def nonlinear_conjugate_gradient(dumbbells, box_size, density, L, max_iter=50, tol=1e-6):
    """Optimize dumbbell positions using Nonlinear Conjugate Gradient (Polak-Ribiere)."""
    dumbbells = dumbbells.flatten()
    _, grad = compute_energy_and_gradient(dumbbells, box_size, density, L)
    direction = -grad
    rsold = np.dot(grad, grad)

    for _ in range(max_iter):
        alpha = line_search(dumbbells, direction, grad, box_size, density, L)
        new_dumbbells = dumbbells + alpha * direction
        new_dumbbells = new_dumbbells.reshape(-1, 2, 3)
        new_dumbbells = new_dumbbells % box_size  # Apply periodic BC
        new_dumbbells = new_dumbbells.flatten()

        _, new_grad = compute_energy_and_gradient(new_dumbbells, box_size, density, L)
        rsnew = np.dot(new_grad, new_grad)

        if np.sqrt(rsnew) < tol:
            break

        beta = max(0, np.dot(new_grad, new_grad - grad) / rsold)
        direction = -new_grad + beta * direction

        dumbbells = new_dumbbells
        grad = new_grad
        rsold = rsnew

    return dumbbells.reshape(-1, 2, 3)

def initialize_dumbbells_random(box_size, num_dumbbells, L):
    """Initialize dumbbells with random positions."""
    dumbbells = np.random.uniform(0, box_size, size=(num_dumbbells, 2, 3))
    for i in range(num_dumbbells):
        vec = np.random.uniform(-1, 1, size=3)
        vec = vec / np.linalg.norm(vec) * L
        dumbbells[i, 1] = dumbbells[i, 0] + vec
    return dumbbells

def optimize_all_densities():
    """Optimize dumbbell positions for all densities and generate statistics."""
    energy_per_density = {density: [] for density in densities}
    residual_per_density = {density: [] for density in densities}
    energies_list = []
    densities_list = sorted(densities)

    print(f"Starting optimization...")
    start_time = time.time()

    for density in densities_list:
        print(f"\nOptimizing for density: {density}")

        volume_per_particle = (4 / 3) * np.pi * radius ** 3
        total_volume = num_dumbbells * 2 * volume_per_particle
        box_size = (total_volume / density) ** (1 / 3)

        density_energies = []
        density_residuals = []

        for config in range(num_configurations):
            print(f" Configuration {config + 1}/{num_configurations}")

            dumbbells = initialize_dumbbells_random(box_size, num_dumbbells, L)
            final_dumbbells = nonlinear_conjugate_gradient(dumbbells.copy(), box_size, density, L)

            # Compute final energy of the optimized configuration
            final_energy, _ = compute_energy_and_gradient(final_dumbbells.flatten(), box_size, density, L)
            energy_per_density[density].append(final_energy)
            density_energies.append(final_energy)

            # Use final energy as residual energy
            residual_energy = final_energy
            residual_per_density[density].append(residual_energy)
            density_residuals.append(residual_energy)

            energies_list.append(final_energy)

        print(f"Energies for density {density}: {density_energies}")
        print(f"Average Energy = {np.mean(density_energies):.4f}")
        print(f"Residual Energies for density {density}: {density_residuals}")
        print(f"Average Residual Energy = {np.mean(density_residuals):.4f}")

    # Plot results
    avg_energies = [np.mean(energy_per_density[d]) for d in densities_list]
    std_energies = [np.std(energy_per_density[d]) for d in densities_list]

    plt.figure(figsize=(10, 6))
    plt.errorbar(densities_list, avg_energies, yerr=std_energies, fmt='o-', capsize=5, color='b', label="Energy")
    plt.axvline(x=density_threshold, color='g', linestyle='--', label="Density threshold (0.65)")
    plt.xlabel('Density')
    plt.ylabel('Energy')
    plt.title(f'Energy vs Density')
    plt.grid(True)
    plt.legend()
    plt.tight_layout()
    plt.show()

if __name__ == "__main__":
    np.random.seed(42)
    optimize_all_densities()