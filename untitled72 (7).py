def compute_distances_and_gradients(positions, box_size):
    """Vectorized computation of distances and gradients with PBC"""
    positions = positions.reshape((num_particles, 3))

    # Create displacement vectors between all pairs of particles
    ri = positions[:, np.newaxis, :]
    rj = positions[np.newaxis, :, :]
    diff = ri - rj

    # Apply minimum image convention (PBC)
    diff = diff - box_size * np.round(diff / box_size)

    # Compute distances
    distances = np.linalg.norm(diff, axis=2)
    np.fill_diagonal(distances, np.inf)  # Avoid self-interactions

    return distances, diff

def objective_function(positions, box_size):
    """Vectorized computation of total energy"""
    distances, _ = compute_distances_and_gradients(positions, box_size)
    overlaps = 2 * radius - distances
    overlaps[overlaps < 0] = 0  # Only consider overlapping particles
    return np.sum(overlaps**2) / 2  # Divide by 2 to avoid double counting

def gradient(positions, box_size):
    """Vectorized computation of gradient"""
    positions = positions.reshape((num_particles, 3))
