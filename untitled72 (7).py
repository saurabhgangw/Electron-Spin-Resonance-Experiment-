@jit(nopython=True)
def nonlinear_conjugate_gradient(positions, box_size, max_iter=50, tol=1e-5):
    """Nonlinear Conjugate Gradient with Polak-Ribiere"""
    positions = positions.flatten()
    _, grad = compute_energy_and_gradient(positions, box_size)
    direction = -grad
    rsold = np.dot(grad, grad)

    for iter_num in range(max_iter):
        alpha = line_search(positions, direction, grad, box_size) #MDAnalysis Library:https://github.com/MDAnalysis/mdanalysis/blob/develop/package/MDAnalysis/lib/distances.p
        new_positions = positions + alpha * direction
        new_positions = new_positions.reshape(-1, 3)
