def compute_distances_vectorized(positions, box_size):
    """Vectorized distance computation with periodic boundary conditions"""
    n = positions.shape[0]
    distances = np.zeros((n, n))
    diffs = np.zeros((n, n, 3))

    for i in range(n):
        diff = positions[i] - positions
        # Apply PBC
        diff = diff - box_size * np.round(diff / box_size)
        diffs[i] = diff
        distances[i] = np.sqrt(np.sum(diff * diff, axis=1))

    np.fill_diagonal(distances, np.inf)
    return distances, diffs

@jit(nopython=True)
def objective_function(positions, box_size):
    """Compute total energy of the system"""
    distances, _ = compute_distances_vectorized(positions, box_size)
    overlaps = 2 * radius - distances
    overlaps = np.maximum(overlaps, 0)
    return np.sum(overlaps * overlaps) / 2

@jit(nopython=True)
def gradient(positions, box_size):
    """Compute gradient of the energy"""
    distances, diffs = compute_distances_vectorized(positions, box_size)
    overlaps = 2 * radius - distances
    mask = overlaps > 0

    grad = np.zeros_like(positions)
    for i in range(len(positions)):
        for j in range(len(positions)):
            if mask[i,j]:
                grad[i] += 2 * overlaps[i,j] * diffs[i,j] / (distances[i,j] + 1e-10)

    return grad

