import numpy as np
import matplotlib.pyplot as plt
from mpl_toolkits.mplot3d import Axes3D

# Number of particles
num_particles = 100
radius = 1.0  # Radius of the spherical particles
desired_density = 0.64  # Desired density

# Calculate bounding box side length
volume_per_particle = (4/3) * np.pi * radius**3
total_volume_particles = num_particles * volume_per_particle
bounding_box_volume = total_volume_particles / desired_density
bounding_box_side_length = bounding_box_volume**(1/3)

# Generate initial random positions for particles
initial_positions = np.random.rand(num_particles, 3) * bounding_box_side_length

# Objective function
def objective_function(positions):
    positions = positions.reshape((num_particles, 3))
    total_energy = 0.0

    for i in range(num_particles):
        for j in range(i + 1, num_particles):
            distance = np.linalg.norm(positions[i] - positions[j])  # Without PBC for now
            overlap = 2 * radius - distance
            if overlap > 0:
                total_energy += overlap**2

    return total_energy

# Gradient of the objective function
def gradient(positions):
    positions = positions.reshape((num_particles, 3))
    grad = np.zeros_like(positions)

    for i in range(num_particles):
        for j in range(num_particles):
            if i != j:
                distance = np.linalg.norm(positions[i] - positions[j])  # Without PBC for now
                overlap = 2 * radius - distance
                if overlap > 0:
                    grad_contribution = 2 * overlap * (positions[i] - positions[j]) / distance
                    grad[i] += grad_contribution

    return grad.flatten()

# Line search to find the optimal step size
def line_search(positions, direction, grad, alpha_init=1.0, c1=1e-4, tau=0.5):
    alpha = alpha_init
    while True:
        new_positions = positions + alpha * direction
        if objective_function(new_positions) <= (
            objective_function(positions) + c1 * alpha * np.dot(grad, direction)
        ):
            break
        alpha *= tau
    return alpha

# Nonlinear Conjugate Gradient Method (Polak-Ribiere)
def nonlinear_conjugate_gradient(objective_function, gradient, initial_positions, max_iter=1000, tol=1e-5):
    positions = initial_positions.flatten()
    grad = gradient(positions)
    direction = -grad  # Initial direction is steepest descent

    for iter_num in range(max_iter):
        # Line search to find step size
        alpha = line_search(positions, direction, grad)

        # Update positions
        new_positions = positions + alpha * direction

        # Compute new gradient
        new_grad = gradient(new_positions)

        # Check for convergence
        if np.linalg.norm(new_grad) < tol:
            print(f"Converged after {iter_num + 1} iterations.")
            break

        # Polak-Ribiere formula for beta
        beta = max(0, np.dot(new_grad, new_grad - grad) / np.dot(grad, grad))

        # Update direction
        direction = -new_grad + beta * direction

        # Update for next iteration
        positions = new_positions
        grad = new_grad

        # Debugging output
        print(f"Iteration {iter_num + 1}: Objective = {objective_function(positions):.6f}")

    return positions

