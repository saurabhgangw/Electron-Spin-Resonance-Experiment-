import numpy as np#NumPy Array Programming: https://numpy.org/doc/stable/reference/arrays.html
import matplotlib.pyplot as plt
from numba import jit, prange
import time
##from painless cg pdf and gradient = np.zeros((2 * n, 3))
# Configuration
num_particles = 100
radius = 1.0
densities = [0.30, 0.38, 0.45, 0.52, 0.59, 0.63, 0.64, 0.69, 0.72]
num_configurations = 5  # Number of configurations per density
density_threshold = 0.65  # Density threshold for energy change

@jit(nopython=True, fastmath=True, parallel=True)#Numba Documentation: https://numba.readthedocs.io/en/stable/user/jit.html
#FastMath Options: https://numba.readthedocs.io/en/stable/user/performance-tips.html#fastmath, #Parallel Features: https://numba.readthedocs.io/en/stable/user/parallel.html
def compute_energy_and_gradient(positions, box_size, density): #Molecular Dynamics Fundamentals: https://doi.org/10.1063/1.445869
    """Compute energy and gradient with periodic boundary conditions."""#Position Representation: https://doi.org/10.1016/j.cpc.2008.01.006
    n = len(positions) // 3
    positions = positions.reshape(n, 3)

    # Modified gradient to account for 2N particles (rotary degrees of freedom)
    gradient = np.zeros((2 * n, 3))  #Rotational Dynamics: https://journals.aps.org/pre/abstract/10.1103/PhysRevE.74.061308
    energy = 0.0 #Angular Momentum in MD: https://doi.org/10.1063/1.4812323,Numba User Guide: https://numba.readthedocs.io/en/stable/user/index.html

    for i in prange(n):#Numba Parallel Documentation: https://numba.readthedocs.io/en/stable/user/parallel.html#automatic-parallelization-with-numba-parallel
        for j in range(i + 1, n):#Parallel Algorithms in MD: https://doi.org/10.1063/1.4812323
            rij = positions[i] - positions[j] #Periodic Boundary Conditions: https://en.wikipedia.org/wiki/Periodic_boundary_conditions
            rij = rij - box_size * np.round(rij / box_size)  # Apply periodic boundaries #LAMMPS PBC Implementation: https://docs.lammps.org/Howto_periodic.html
            dist2 = np.sum(rij * rij) #Distance Calculations in MD: https://doi.org/10.1016/j.cpc.2008.01.006

            if dist2 < (2 * radius) ** 2:  # Interaction range (soft spheres)Soft Sphere Model: https://journals.aps.org/pre/abstract/10.1103/PhysRevE.68.011306
                dist = np.sqrt(dist2)
                overlap = 2 * radius - dist# Jamming Transitions: https://journals.aps.org/prl/abstract/10.1103/PhysRevLett.88.075507,Force Fields in MD: https://doi.org/10.1063/1.445869
                if overlap > 0:
                    if density < density_threshold:
                        energy += 0  # No penalty before threshold
                    else:
                        energy += overlap**2  # Penalty based on overlap squared

                    grad_mag = 2 * overlap / dist  # Gradient magnitude ,Gradient-Based Optimization: https://doi.org/10.1137/S1052623497318992
                    gradient[i] += grad_mag * rij #Force Fields in MD: https://doi.org/10.1063/1.445869
                    gradient[j] -= grad_mag * rij

    # Return only the first N rows of the gradient (translational degrees of freedom)
    return energy, gradient[:n].flatten()


@jit(nopython=True)#Official Numba Documentation: https://numba.readthedocs.io/en/stable/user/jit.html
def line_search(positions, direction, grad, box_size, density, alpha_init=1.0, c1=1e-6, tau=0.7):#Implementation Guide: https://doi.org/10.1007/978-0-387-40065-5_3
    """Backtracking line search.""" #Line Search Methods in Molecular Dynamics,Link: https://doi.org/10.1063/1.445869
    alpha = alpha_init
    f0, _ = compute_energy_and_gradient(positions, box_size, density)
    descent = np.dot(grad, direction)

    for _ in range(10):
        new_positions = positions + alpha * direction
        f_new, _ = compute_energy_and_gradient(new_positions, box_size, density)
        if f_new <= f0 + c1 * alpha * descent: #Theoretical Background: https://en.wikipedia.org/wiki/Wolfe_conditions
            break #Mathematical Analysis: https://doi.org/10.1137/S1052623497318992
        alpha *= tau

    return alpha


@jit(nopython=True)
def nonlinear_conjugate_gradient(positions, box_size, density, max_iter=50, tol=1e-6):#  Method: https://doi.org/10.1007/BF01589116
    """Nonlinear Conjugate Gradient with Polak-Ribiere.""" #Mathematical Foundation: https://en.wikipedia.org/wiki/Nonlinear_conjugate_gradient_method
    positions = positions.flatten()
    _, grad = compute_energy_and_gradient(positions, box_size, density)
    direction = -grad
    rsold = np.dot(grad, grad)

    for _ in range(max_iter):
        # Line search for step size alpha
        alpha = line_search(positions, direction, grad, box_size, density)
        new_positions = positions + alpha * direction
        new_positions = new_positions.reshape(-1, 3)
        new_positions = new_positions % box_size  # Apply periodic boundary conditions, Implementation Guide: https://docs.lammps.org/Howto_periodic.html
        new_positions = new_positions.flatten()   #Theory: https://en.wikipedia.org/wiki/Periodic_boundary_conditions

        # Compute new gradient
        _, new_grad = compute_energy_and_gradient(new_positions, box_size, density)
        rsnew = np.dot(new_grad, new_grad)

        if rsnew < tol**2:  # Check for convergence Convergence Analysis: https://doi.org/10.1137/S1052623403428793
            break

        # Polak-Ribiere beta Link: http://www.cs.cmu.edu/~quake-papers/painless-conjugate-gradient.pdf
        beta = max(0, np.dot(new_grad, new_grad - grad) / rsold)

        # Update direction
        direction = -new_grad + beta * direction
        grad = new_grad
        rsold = rsnew

        # Update positions
        positions = new_positions

    return positions.reshape(-1, 3)


def initialize_positions_random(box_size, num_particles):#NumPy Array Shape Reference: https://numpy.org/doc/stable/reference/generated/numpy.ndarray.shape.html
    """Initialize positions randomly within the box."""
    return np.random.uniform(0, box_size, size=(num_particles, 3))


def optimize_all_densities():#Python Dictionary Comprehension: https://docs.python.org/3/tutorial/datastructures.html#dictionary-comprehension
    """Optimize particle positions for all densities and compute average energies."""
    #Density-Dependent Energy Optimization Link: https://doi.org/10.1103/PhysRevE.70.043301
    energy_per_density = {density: [] for density in densities}

    print("Starting optimization for all densities...")
    start_time = time.time() #time.time() Reference: https://docs.python.org/3/library/time.html#time.time

    for density in densities:
        print(f"\nOptimizing for density: {density}")

        # Calculate box size based on density
        volume_per_particle = (4 / 3) * np.pi * radius ** 3
        total_volume = num_particles * volume_per_particle
        box_size = (total_volume / density) ** (1 / 3)

        for config in range(num_configurations):#Python Loops Documentation: https://docs.python.org/3/tutorial/controlflow.html#for-statements
            # Initialize positions randomly
            positions = initialize_positions_random(box_size, num_particles)#Particle System Initialization: https://doi.org/10.1016/j.cpc.2008.01.006

            # Optimize positions using conjugate gradient
            final_positions = nonlinear_conjugate_gradient(positions.copy(), box_size, density)

            # Compute final energy
            final_energy, _ = compute_energy_and_gradient(final_positions.flatten(), box_size, density)#mplementation Guide: https://doi.org/10.1137/S1052623497318992
            energy_per_density[density].append(final_energy) #Energy Calculations: https://doi.org/10.1063/1.445869

    end_time = time.time()#Python Time Module: https://docs.python.org/3/library/time.html
    print(f"\nTotal optimization time: {end_time - start_time:.2f} seconds")

    # Compute average and standard deviation of energies, Python Sorting: https://docs.python.org/3/howto/sorting.html
    densities_list = sorted(densities) #List Comprehension Guide: https://docs.python.org/3/tutorial/datastructures.html#list-comprehensions
    avg_energies = [np.mean(energy_per_density[d]) for d in densities_list]#NumPy Standard Deviation: https://numpy.org/doc/stable/reference/generated/numpy.std.html
    std_energies = [np.std(energy_per_density[d]) for d in densities_list]#Statistical Functions Overview: https://numpy.org/doc/stable/reference/routines.statistics.html

    # Plot graph
    plt.figure(figsize=(10, 6))#Matplotlib Figure: https://matplotlib.org/stable/api/_as_gen/matplotlib.pyplot.figure.html,size Parameters: https://matplotlib.org/stable/api/_as_gen/matplotlib.pyplot.figure.html#matplotlib.pyplot.figure
    plt.errorbar(densities_list, avg_energies, yerr=std_energies, fmt='o-', capsize=5, color='b', label="Energy")#Errorbar Documentation: https://matplotlib.org/stable/api/_as_gen/matplotlib.pyplot.errorbar.html
    plt.axvline(x=density_threshold, color='r', linestyle='--', label="Density threshold (0.65)")
    plt.xlabel('Density')#Format Strings: https://matplotlib.org/stable/api/_as_gen/matplotlib.pyplot.plot.html#matplotlib.pyplot.plot
    plt.ylabel('Average Energy')#Labels: https://matplotlib.org/stable/api/_as_gen/matplotlib.pyplot.xlabel.html
    plt.title('Average Energy vs Density (Soft Sphere Optimization)')#Titles: https://matplotlib.org/stable/api/_as_gen/matplotlib.pyplot.title.html
    plt.grid(True)#Grid: https://matplotlib.org/stable/api/_as_gen/matplotlib.pyplot.grid.html
    plt.legend()#Legend: https://matplotlib.org/stable/api/_as_gen/matplotlib.pyplot.legend.html
    plt.tight_layout()#Layout: https://matplotlib.org/stable/api/_as_gen/matplotlib.pyplot.tight_layout.html

    # Print numerical results
    print("\nResults for each density:")
    for density in densities_list:# Python Dictionary Documentation: https://docs.python.org/3/tutorial/datastructures.html#dictionaries
        mean_energy = np.mean(energy_per_density[density])#NumPy Mean Documentation: https://numpy.org/doc/stable/reference/generated/numpy.mean.html
        std_energy = np.std(energy_per_density[density])#NumPy Standard Deviation: https://numpy.org/doc/stable/reference/generated/numpy.std.html
        print(f"Density {density:.2f}:  Optimized Energy: {mean_energy:.4f} ± {std_energy:.4f}")

    plt.show()


if __name__ == "__main__":#Official Python Documentation: https://docs.python.org/3/library/__main__.html
    optimize_all_densities()